export function t(key, vars) {
  const lang = document.documentElement.lang === 'id' ? 'id' : 'en';
  let str = DICT[key]?.[lang] ?? DICT[key]?.en ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, v);
    });
  }
  return str;
}

function applyToDom() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.dataset.i18nTitle));
  });
}

export function applyLang(lang, persist = true) {
  document.documentElement.lang = lang;
  // persist=false is used on initial load for an auto-detected language —
  // we don't want to lock that into localStorage, or the browser-detection
  // priority rule (manual > browser > fallback) would only ever run once.
  // A real user pick (persist=true, the default) always overrides it.
  if (persist) localStorage.setItem(STORAGE_KEY, lang);
  applyToDom();
  window.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang } }));
  document.querySelectorAll('[data-lang-option]').forEach((btn) => {
    btn.classList.toggle('is-active', btn.dataset.langOption === lang);
  });
}

function initLang() {
  // document.documentElement.lang was already set correctly pre-paint by the
  // inline script in index.html (manual choice, or browser detection as
  // fallback) — just sync the DOM text to it, without re-persisting.
  applyLang(document.documentElement.lang === 'id' ? 'id' : 'en', false);
  document.querySelectorAll('[data-lang-option]').forEach((btn) => {
    btn.addEventListener('click', () => applyLang(btn.dataset.langOption, true));
  });
}

